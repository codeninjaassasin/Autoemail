#!/usr/bin/env node
/**
 * Turns the WireGuard configs in proxies/ into a docker-compose stack where
 * each one runs in its own container exposing a local HTTP proxy.
 *
 * Why containers rather than `wg-quick up`: wg-quick rewrites the host's
 * routing table, so every application on the machine goes through the VPN.
 * A container keeps the tunnel inside its own network namespace, so only the
 * scraper's browser uses it — and because they're separate namespaces, all
 * five run at once, which is what makes per-post rotation across them
 * possible at all.
 *
 * Secrets: the private key is written to vpn/.env (gitignored) and referenced
 * from the compose file, so the compose file itself stays safe to read and
 * share.
 */
const fs = require('fs');
const path = require('path');
const dns = require('dns').promises;

const ROOT = path.join(__dirname, '..');
const CONF_DIR = fs.existsSync(path.join(ROOT, 'proxies'))
  ? path.join(ROOT, 'proxies')
  : path.join(ROOT, 'Proxies');
const OUT_DIR = path.join(ROOT, 'vpn');
// gluetun selects a Surfshark server by city, which keeps the address and the
// peer key matched. Airport codes in the filenames map to those city names.
const CITY = { 'us-clt': 'Charlotte', 'us-dtw': 'Detroit', 'us-hou': 'Houston', 'us-oma': 'Omaha', 'us-phx': 'Phoenix' };
const BASE_PORT = Number(process.env.VPN_BASE_PORT ?? 8881);

function parseConf(text) {
  const get = (key) => {
    const m = text.match(new RegExp(`^${key}\\s*=\\s*(.+)$`, 'm'));
    return m ? m[1].trim() : '';
  };
  return {
    privateKey: get('PrivateKey'),
    address: get('Address'),
    dns: get('DNS'),
    publicKey: get('PublicKey'),
    endpoint: get('Endpoint'),
  };
}

(async () => {
  if (!fs.existsSync(CONF_DIR)) {
    console.error(`No config directory at ${CONF_DIR}`);
    process.exit(1);
  }
  const files = fs.readdirSync(CONF_DIR).filter((f) => f.endsWith('.conf')).sort();
  if (files.length === 0) {
    console.error(`No .conf files in ${CONF_DIR}`);
    process.exit(1);
  }

  const services = [];
  const proxies = [];
  const keyLines = [];

  for (const [i, file] of files.entries()) {
    const conf = parseConf(fs.readFileSync(path.join(CONF_DIR, file), 'utf8'));
    const name = path.basename(file, '.conf');
    const [host, port] = conf.endpoint.split(':');

    // Resolved only for display. It deliberately isn't pinned into the
    // compose file: Surfshark round-robins these hostnames across servers that
    // each have their own WireGuard public key, so a resolved IP is very
    // likely paired with a key it doesn't own — the handshake is then rejected
    // in silence and the tunnel comes up carrying no traffic. gluetun's own
    // Surfshark provider keeps server addresses and keys matched, so it picks.
    let ip = host;
    try {
      ip = (await dns.resolve4(host))[0];
    } catch {
      ip = '(unresolved)';
    }

    // Each config carries its own key — Surfshark does not reuse one per
    // account, and assuming it did silently handed four of five containers a
    // key the server rejected. WireGuard fails silently, so the tunnel came up
    // and simply passed no traffic.
    const envKey = `WG_PRIVATE_KEY_${name.toUpperCase().replace(/[^A-Z0-9]/g, '_')}`;
    keyLines.push(`${envKey}=${conf.privateKey}`);

    const hostPort = BASE_PORT + i;
    proxies.push({ name, url: `http://127.0.0.1:${hostPort}`, endpoint: `${host} (${ip})` });

    services.push(
      `  vpn-${name}:\n` +
      `    image: qmcgaw/gluetun:latest\n` +
      `    container_name: vpn-${name}\n` +
      `    cap_add:\n      - NET_ADMIN\n` +
      `    devices:\n      - /dev/net/tun:/dev/net/tun\n` +
      `    environment:\n` +
      `      - VPN_SERVICE_PROVIDER=surfshark\n` +
      `      - VPN_TYPE=wireguard\n` +
      `      - SERVER_CITIES=${CITY[name] || name}\n` +
      `      - WIREGUARD_PRIVATE_KEY=\${${envKey}}\n` +
      `      - WIREGUARD_ADDRESSES=${conf.address}\n` +
      // The whole point: a proxy the host can reach, tunnel-side only.
      `      - HTTPPROXY=on\n` +
      `      - HTTPPROXY_LISTENING_ADDRESS=:8888\n` +
      `      - HTTPPROXY_LOG=off\n` +
      `    ports:\n      - "${hostPort}:8888"\n` +
      `    restart: unless-stopped\n`
    );
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  fs.writeFileSync(
    path.join(OUT_DIR, 'docker-compose.yml'),
    '# Generated by scripts/build-vpn-proxies.js — do not edit by hand.\n' +
      '# Each service tunnels through one WireGuard config and exposes an HTTP\n' +
      '# proxy on the host, so only clients that opt in are routed through it.\n' +
      'services:\n' +
      services.join('\n')
  );

  // Secret lives here, and .gitignore already covers .env at any depth.
  fs.writeFileSync(path.join(OUT_DIR, '.env'), keyLines.join('\n') + '\n');
  fs.chmodSync(path.join(OUT_DIR, '.env'), 0o600);

  const list = proxies.map((p) => p.url).join(',');
  fs.writeFileSync(path.join(OUT_DIR, 'proxies.txt'), proxies.map((p) => p.url).join('\n') + '\n');

  console.log(`Wrote vpn/docker-compose.yml for ${proxies.length} tunnels:\n`);
  for (const p of proxies) console.log(`   ${p.name.padEnd(8)} ${p.url.padEnd(24)} → ${p.endpoint}`);
  console.log(`\nvpn/.env holds the private key (chmod 600, gitignored).`);
  console.log(`\nStart:  docker compose -f vpn/docker-compose.yml up -d`);
  console.log(`Use:    PROXY_STATIC="${list}" npm start`);
  console.log(`Stop:   docker compose -f vpn/docker-compose.yml down`);
})();
